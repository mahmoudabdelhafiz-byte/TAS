-- 025: the terminal's own gate system. A terminal that runs the truck appointment system without Yardsyncs Autogate
-- connects its existing gate (OCR portal, kiosk, gate operating system) through the gate API with a key per system.
-- Each key acts as its own gate clerk account (no password, can't sign in), so access rules and the history work as
-- for a person at the gate. Only the key's SHA-256 is kept.

CREATE TABLE IF NOT EXISTS gate_system_key (
    key_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id   integer      NOT NULL REFERENCES terminal(terminal_id),
    user_id       integer      NOT NULL UNIQUE REFERENCES app_user(user_id),  -- the gate clerk account the key acts as
    name          varchar(60)  NOT NULL,                     -- e.g. "North gate OCR portal"
    key_hash      char(64)     NOT NULL UNIQUE,              -- SHA-256 of the key (hex)
    key_hint      varchar(12)  NOT NULL,                     -- the key's last characters, to tell keys apart
    created_at    timestamptz  NOT NULL DEFAULT now(),
    created_by    integer      NULL REFERENCES app_user(user_id),
    last_used_at  timestamptz  NULL,
    revoked_at    timestamptz  NULL,
    revoked_by    integer      NULL REFERENCES app_user(user_id)
);
CREATE INDEX IF NOT EXISTS ix_gate_system_key_terminal ON gate_system_key (terminal_id);
