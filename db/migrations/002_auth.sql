-- Adds authentication to a database created from schema v0.2.
-- New databases: just run db/schema.sql (it already contains this).

ALTER TABLE app_user
    ADD COLUMN password_hash      varchar(200) NULL,
    ADD COLUMN failed_login_count integer      NOT NULL DEFAULT 0,
    ADD COLUMN locked_until       timestamptz  NULL,
    ADD COLUMN last_login_at      timestamptz  NULL,
    ADD COLUMN created_at         timestamptz  NOT NULL DEFAULT now();

CREATE TABLE refresh_token (
    refresh_token_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer      NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    token_hash        bytea        NOT NULL UNIQUE,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    expires_at        timestamptz  NOT NULL,
    revoked_at        timestamptz  NULL,
    replaced_by_hash  bytea        NULL,
    created_ip        varchar(45)  NULL
);
CREATE INDEX ix_refresh_token_user ON refresh_token(user_id) WHERE revoked_at IS NULL;

-- Emails are matched case-insensitively; store them lower-case.
UPDATE app_user SET email = lower(email);
