-- 006: driver app sign-in with a one-time code by SMS.
-- Codes are stored only as hashes and expire after a few minutes.

CREATE TABLE driver_otp (
    otp_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mobile       varchar(20)  NOT NULL,          -- E.164, e.g. +966500000001
    install_id   varchar(64)  NOT NULL,          -- the app install that asked for the code
    code_hash    bytea        NOT NULL,
    attempts     integer      NOT NULL DEFAULT 0,
    expires_at   timestamptz  NOT NULL,
    consumed_at  timestamptz  NULL,
    created_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_driver_otp_mobile ON driver_otp(mobile, created_at);
