-- 018: the Autogate lane model. Each gate lane has a state (open, closed, out of order) set by the gate staff with a
-- note, and a way of working (manual: a clerk at the lane; automatic: the lane decides and refers exceptions).
-- The devices at a lane (cameras, OCR, RFID reader, kiosk, barrier, traffic light, display, printer, intercom,
-- weighbridge) are recorded per lane, vendor-neutral, with what each one reads.

ALTER TABLE gate_lane ADD COLUMN IF NOT EXISTS lane_state varchar(12) NOT NULL DEFAULT 'OPEN'
    CHECK (lane_state IN ('OPEN','CLOSED','OUT_OF_ORDER'));
ALTER TABLE gate_lane ADD COLUMN IF NOT EXISTS operation_mode varchar(10) NOT NULL DEFAULT 'MANUAL'
    CHECK (operation_mode IN ('MANUAL','AUTOMATIC'));
ALTER TABLE gate_lane ADD COLUMN IF NOT EXISTS state_note varchar(200) NULL;
ALTER TABLE gate_lane ADD COLUMN IF NOT EXISTS state_changed_at timestamptz NULL;
ALTER TABLE gate_lane ADD COLUMN IF NOT EXISTS state_changed_by integer NULL;   -- app_user.user_id

CREATE TABLE IF NOT EXISTS gate_lane_device (
    device_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id  integer      NOT NULL REFERENCES terminal(terminal_id),
    lane_id      integer      NOT NULL REFERENCES gate_lane(lane_id) ON DELETE CASCADE,
    device_code  varchar(30)  NOT NULL,
    kind         varchar(15)  NOT NULL CHECK (kind IN
                   ('CAMERA','OCR','RFID_READER','KIOSK','BARRIER','TRAFFIC_LIGHT','DISPLAY','PRINTER','INTERCOM','WEIGHBRIDGE')),
    reads        varchar(80)  NULL,   -- cameras / OCR: PLATE,CONTAINER,ISO_CODE,SEAL,DAMAGE; RFID readers: TAG
    vendor       varchar(60)  NULL,
    model        varchar(60)  NULL,
    address      varchar(200) NULL,   -- IP address, URL or port the lane controller uses
    is_active    boolean      NOT NULL DEFAULT true,
    notes        varchar(200) NULL,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (terminal_id, device_code)
);

CREATE INDEX IF NOT EXISTS ix_lane_device_lane ON gate_lane_device (lane_id);
