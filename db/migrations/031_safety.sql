-- 031: safety in the driver app. Campaigns: a notice (title, text, optional picture) in the drivers' languages for a
-- period, to all drivers or some companies' drivers, read and confirmed in the app ("I have read it"). Induction: the
-- terminal's short safety course (pages, then questions); a driver passes it once and it stays valid for some months.
-- The gate warns about, or sends to the trouble desk, a driver without a valid induction (terminal setting
-- induction_mode). Confirmations and passes are kept per person (mobile number), across the companies they drive for.

CREATE TABLE IF NOT EXISTS safety_campaign (
    campaign_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id    integer      NOT NULL REFERENCES terminal(terminal_id),
    texts          jsonb        NOT NULL,          -- {"en": {"title": "…", "body": "…"}, "ar": {…}, …}
    image_url      varchar(400) NULL,              -- https picture hosted by the terminal
    starts_on      date         NOT NULL,
    ends_on        date         NOT NULL,
    company_ids    integer[]    NULL,              -- null = every driver
    require_ack    boolean      NOT NULL DEFAULT true,
    created_by     integer      NULL REFERENCES app_user(user_id),
    created_at     timestamptz  NOT NULL DEFAULT now(),
    archived_at    timestamptz  NULL
);
CREATE INDEX IF NOT EXISTS ix_safety_campaign_terminal ON safety_campaign (terminal_id, ends_on);

CREATE TABLE IF NOT EXISTS safety_ack (
    campaign_id    integer      NOT NULL REFERENCES safety_campaign(campaign_id),
    mobile         varchar(20)  NOT NULL,
    driver_id      integer      NOT NULL REFERENCES driver(driver_id),
    acked_at       timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, mobile)
);

CREATE TABLE IF NOT EXISTS safety_induction (
    induction_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id    integer      NOT NULL UNIQUE REFERENCES terminal(terminal_id),
    pages          jsonb        NOT NULL,          -- [{"en": {"title": "…", "body": "…"}, "ar": {…}}]
    questions      jsonb        NOT NULL,          -- [{"texts": {"en": {"question": "…", "options": ["…"]}}, "correct": 1}]
    valid_months   integer      NOT NULL DEFAULT 12 CHECK (valid_months BETWEEN 1 AND 60),
    version        integer      NOT NULL DEFAULT 1,
    updated_by     integer      NULL REFERENCES app_user(user_id),
    updated_at     timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS induction_pass (
    pass_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id    integer      NOT NULL REFERENCES terminal(terminal_id),
    mobile         varchar(20)  NOT NULL,
    driver_id      integer      NOT NULL REFERENCES driver(driver_id),
    version        integer      NOT NULL,
    passed_at      timestamptz  NOT NULL DEFAULT now(),
    valid_until    timestamptz  NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_induction_pass_person ON induction_pass (terminal_id, mobile, valid_until);
