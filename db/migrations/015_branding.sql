-- 015: branding. The installation's own (operator_id NULL, one row at most) and one per operator: the name in the
-- portal, the app and messages, the main colour, the logo, and the web address an operator's people sign in at.

CREATE TABLE IF NOT EXISTS branding (
    branding_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id  integer      NULL UNIQUE REFERENCES terminal_operator(operator_id) ON DELETE CASCADE,
    name         varchar(80)  NULL,
    color        char(7)      NULL CHECK (color ~ '^#[0-9a-f]{6}$'),
    domain       varchar(200) NULL UNIQUE,
    logo         bytea        NULL,
    logo_type    varchar(20)  NULL CHECK (logo_type IN ('image/png','image/jpeg','image/webp')),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_branding_installation ON branding ((operator_id IS NULL)) WHERE operator_id IS NULL;
