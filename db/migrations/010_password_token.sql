-- 010: links to set a password: "forgot password" (RESET, 60 min) and invitations for new users (INVITE, 7 days).
-- Only a SHA-256 hash of the link's token is stored; a link works once.

CREATE TABLE password_token (
    token_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      integer      NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    purpose      varchar(10)  NOT NULL CHECK (purpose IN ('RESET','INVITE')),
    token_hash   bytea        NOT NULL UNIQUE,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    expires_at   timestamptz  NOT NULL,
    used_at      timestamptz  NULL,
    created_by   integer      NULL REFERENCES app_user(user_id)
);
CREATE INDEX ix_password_token_user ON password_token(user_id, created_at);
