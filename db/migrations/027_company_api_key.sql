-- 027: trucking companies' own systems (TMS, dispatch) on the API with a key instead of a person's sign-in. Each key
-- acts as its own company user account (no password, can't sign in): BOOK keys book and change appointments, READ
-- keys only look. Made and revoked by the company's admin. Only the key's SHA-256 is kept.

CREATE TABLE IF NOT EXISTS company_api_key (
    key_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    integer      NOT NULL REFERENCES company(company_id),
    user_id       integer      NOT NULL UNIQUE REFERENCES app_user(user_id),  -- the company user account the key acts as
    name          varchar(60)  NOT NULL,                     -- e.g. "Our TMS"
    scope         varchar(4)   NOT NULL CHECK (scope IN ('BOOK','READ')),
    key_hash      char(64)     NOT NULL UNIQUE,              -- SHA-256 of the key (hex)
    key_hint      varchar(12)  NOT NULL,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    created_by    integer      NULL REFERENCES app_user(user_id),
    last_used_at  timestamptz  NULL,
    revoked_at    timestamptz  NULL,
    revoked_by    integer      NULL REFERENCES app_user(user_id)
);
CREATE INDEX IF NOT EXISTS ix_company_api_key_company ON company_api_key (company_id);
