-- 008: events for the terminal's own systems (TOS, control room, yard management), e.g. "truck at block B2".
-- Every event is kept here; it is delivered to the terminal's webhook when one is configured for that event type
-- (Integration:Terminals:<code> in the API configuration), otherwise marked SKIPPED.

CREATE TABLE integration_event (
    event_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id      integer      NOT NULL REFERENCES terminal(terminal_id),
    event_type       varchar(30)  NOT NULL,   -- TRUCK_CHECKED_IN, TRUCK_AT_BLOCK, STOP_COMPLETED
    appointment_id   bigint       NULL REFERENCES appointment(appointment_id),
    payload          jsonb        NOT NULL,
    status           varchar(10)  NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED','SENT','FAILED','SKIPPED')),
    attempts         integer      NOT NULL DEFAULT 0,
    last_error       varchar(400) NULL,
    next_attempt_at  timestamptz  NULL,
    created_at       timestamptz  NOT NULL DEFAULT now(),
    sent_at          timestamptz  NULL
);
CREATE INDEX ix_integration_event_due ON integration_event(status, next_attempt_at);
CREATE INDEX ix_integration_event_terminal ON integration_event(terminal_id, created_at DESC);
