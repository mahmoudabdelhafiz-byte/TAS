-- Gate trouble desk (schema v0.4 -> v0.5).

CREATE TABLE gate_trouble (
    trouble_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id      integer      NOT NULL REFERENCES terminal(terminal_id),
    lane_id          integer      NULL REFERENCES gate_lane(lane_id),
    appointment_id   bigint       NULL REFERENCES appointment(appointment_id),
    plate_read       varchar(20)  NULL,
    container_reads  varchar(60)  NULL,
    reason_code      varchar(20)  NOT NULL CHECK (reason_code IN
                       ('NO_APPOINTMENT','EARLY','LATE','NOT_CLEARED','BLOCKED','ALREADY_IN','CANCELLED')),
    reason_text      varchar(400) NOT NULL,
    status           varchar(10)  NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED')),
    resolution       varchar(15)  NULL CHECK (resolution IN ('ADMITTED','REJECTED','WALK_IN','DISMISSED')),
    resolution_note  varchar(300) NULL,
    resolved_by      integer      NULL REFERENCES app_user(user_id),
    resolved_at      timestamptz  NULL,
    created_at       timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_gate_trouble_open ON gate_trouble(terminal_id, status, created_at);
