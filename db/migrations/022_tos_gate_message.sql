-- 022: gate passages recorded in the TOS. Each gate-in and gate-out of a terminal that records them (setting
-- tos_gate_write) is queued here and sent by a worker, retried while the TOS can't be reached, so the gate never
-- waits for the TOS and nothing is lost. Gate-out waits for its gate-in. The TOS's visit key comes back on gate-in.

CREATE TABLE IF NOT EXISTS tos_gate_message (
    message_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id      integer      NOT NULL REFERENCES terminal(terminal_id),
    appointment_id   bigint       NOT NULL REFERENCES appointment(appointment_id) ON DELETE CASCADE,
    stage            varchar(8)   NOT NULL CHECK (stage IN ('GATE_IN','GATE_OUT')),
    lane_code        varchar(20)  NULL,
    occurred_at      timestamptz  NOT NULL,
    status           varchar(6)   NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED','SENT','FAILED')),
    attempts         integer      NOT NULL DEFAULT 0,
    next_attempt_at  timestamptz  NOT NULL,
    sent_at          timestamptz  NULL,
    tos_reference    varchar(60)  NULL,   -- the TOS's truck visit key
    last_error       varchar(400) NULL,
    created_at       timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (appointment_id, stage)
);
CREATE INDEX IF NOT EXISTS ix_tos_gate_due ON tos_gate_message (next_attempt_at) WHERE status = 'QUEUED';
