-- 011: containers a portal user follows; they get an email the moment one becomes ready to collect.

CREATE TABLE container_watch (
    watch_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id      integer      NOT NULL REFERENCES terminal(terminal_id),
    user_id          integer      NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    container_no     varchar(11)  NOT NULL,
    last_state       varchar(15)  NULL,      -- READY, NOT_AVAILABLE, ON_HOLD, BOOKED, COLLECTED …
    last_message     varchar(300) NULL,
    last_checked_at  timestamptz  NULL,
    ready_notified_at timestamptz NULL,
    created_at       timestamptz  NOT NULL DEFAULT now(),
    ended_at         timestamptz  NULL,      -- removed by the user, collected, or older than 30 days
    UNIQUE (terminal_id, user_id, container_no)
);
CREATE INDEX ix_container_watch_due ON container_watch(ended_at, last_checked_at);
