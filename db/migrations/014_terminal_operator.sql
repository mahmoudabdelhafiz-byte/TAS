-- 014: terminal operators. An operator runs several terminals on one installation and has its own administrators
-- (OPERATOR_ADMIN), who manage every terminal of the operator. Competitors are kept apart by separate installations.

CREATE TABLE IF NOT EXISTS terminal_operator (
    operator_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         varchar(20)  NOT NULL UNIQUE,
    name         varchar(150) NOT NULL,
    is_active    boolean      NOT NULL DEFAULT true,
    created_at   timestamptz  NOT NULL DEFAULT now()
);

ALTER TABLE terminal ADD COLUMN IF NOT EXISTS operator_id integer NULL REFERENCES terminal_operator(operator_id);
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS operator_id integer NULL REFERENCES terminal_operator(operator_id);

ALTER TABLE app_user DROP CONSTRAINT IF EXISTS app_user_role_check;
ALTER TABLE app_user ADD CONSTRAINT app_user_role_check
    CHECK (role IN ('COMPANY_ADMIN','COMPANY_USER','GATE_CLERK','PLANNER','TERMINAL_ADMIN','OPERATOR_ADMIN','SYS_ADMIN'));

CREATE INDEX IF NOT EXISTS ix_terminal_operator ON terminal (operator_id) WHERE operator_id IS NOT NULL;
