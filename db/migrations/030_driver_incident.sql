-- 030: the driver record. Terminal staff record penalties and misbehaviour against a driver (speeding, no PPE…) with
-- points; points count for a period (terminal setting driver_points_days) and, past the terminal's thresholds, warn
-- the gate and the control room or send the driver to the trouble desk. The driver sees the record in the app and can
-- dispute an entry; planners and terminal admins decide. Withdrawn entries stay, with who withdrew them and why.

CREATE TABLE IF NOT EXISTS driver_incident (
    incident_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id       integer      NOT NULL REFERENCES terminal(terminal_id),
    driver_id         integer      NOT NULL REFERENCES driver(driver_id),
    appointment_id    bigint       NULL REFERENCES appointment(appointment_id),
    kind              varchar(20)  NOT NULL CHECK (kind IN ('SPEEDING','UNSAFE_DRIVING','NO_PPE','WRONG_AREA','DAMAGE','ABUSIVE','NO_SHOW','OTHER')),
    points            smallint     NOT NULL CHECK (points BETWEEN 1 AND 10),
    occurred_at       timestamptz  NOT NULL,
    note              varchar(500) NULL,
    recorded_by       integer      NULL REFERENCES app_user(user_id),
    recorded_at       timestamptz  NOT NULL DEFAULT now(),
    dispute_status    varchar(10)  NULL CHECK (dispute_status IN ('OPEN','ACCEPTED','REJECTED')),
    dispute_text      varchar(500) NULL,
    disputed_at       timestamptz  NULL,
    dispute_answer    varchar(500) NULL,
    decided_by        integer      NULL REFERENCES app_user(user_id),
    decided_at        timestamptz  NULL,
    withdrawn_at      timestamptz  NULL,
    withdrawn_by      integer      NULL REFERENCES app_user(user_id),
    withdraw_reason   varchar(300) NULL
);
CREATE INDEX IF NOT EXISTS ix_driver_incident_driver ON driver_incident (driver_id, occurred_at);
CREATE INDEX IF NOT EXISTS ix_driver_incident_terminal ON driver_incident (terminal_id, occurred_at);
