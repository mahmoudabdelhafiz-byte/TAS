-- 019: Autogate device adapters. Each lane device (or the vendor adapter speaking for it) signs in with its own key,
-- reports that it is alive and healthy, sends what it read (plate, containers with ISO code, seals, damage photos,
-- RFID tag, kiosk entries, weight), and fetches the commands for it (barrier open / close, light red / green / off,
-- display text, ticket print), confirming each one. Vendor-neutral: one format whatever the make.

ALTER TABLE gate_lane_device ADD COLUMN IF NOT EXISTS key_hash char(64) NULL;   -- SHA-256 of the device key (hex)
ALTER TABLE gate_lane_device ADD COLUMN IF NOT EXISTS key_set_at timestamptz NULL;
ALTER TABLE gate_lane_device ADD COLUMN IF NOT EXISTS last_seen_at timestamptz NULL;
ALTER TABLE gate_lane_device ADD COLUMN IF NOT EXISTS reported_status varchar(5) NULL CHECK (reported_status IN ('OK','FAULT'));
ALTER TABLE gate_lane_device ADD COLUMN IF NOT EXISTS status_detail varchar(200) NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_lane_device_key ON gate_lane_device (key_hash) WHERE key_hash IS NOT NULL;

CREATE TABLE IF NOT EXISTS lane_device_read (
    read_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id       integer      NOT NULL REFERENCES terminal(terminal_id),
    lane_id           integer      NOT NULL REFERENCES gate_lane(lane_id) ON DELETE CASCADE,
    device_id         integer      NOT NULL REFERENCES gate_lane_device(device_id) ON DELETE CASCADE,
    read_at           timestamptz  NOT NULL,                 -- when the device read it
    received_at       timestamptz  NOT NULL DEFAULT now(),
    plate             varchar(20)  NULL,                     -- normalized
    plate_confidence  smallint     NULL CHECK (plate_confidence BETWEEN 0 AND 100),
    container_no      varchar(11)  NULL,                     -- the first container read, normalized
    payload           jsonb        NOT NULL DEFAULT '{}'     -- the whole read, normalized: containers, seals, damage, photos, tag, kiosk entry, weight
);
CREATE INDEX IF NOT EXISTS ix_lane_read_lane_time ON lane_device_read (lane_id, received_at);
CREATE INDEX IF NOT EXISTS ix_lane_read_time ON lane_device_read (received_at);

CREATE TABLE IF NOT EXISTS lane_device_command (
    command_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id    integer      NOT NULL REFERENCES terminal(terminal_id),
    lane_id        integer      NOT NULL REFERENCES gate_lane(lane_id) ON DELETE CASCADE,
    device_id      integer      NOT NULL REFERENCES gate_lane_device(device_id) ON DELETE CASCADE,
    command        varchar(6)   NOT NULL CHECK (command IN ('OPEN','CLOSE','RED','GREEN','OFF','SHOW','CLEAR','PRINT')),
    text           varchar(400) NULL,                        -- display / ticket text
    created_at     timestamptz  NOT NULL DEFAULT now(),
    created_by     integer      NULL,                        -- app_user.user_id; NULL = the lane itself
    expires_at     timestamptz  NOT NULL,                    -- not carried out after this (a late barrier opening is unsafe)
    delivered_at   timestamptz  NULL,
    done_at        timestamptz  NULL,
    result         varchar(6)   NULL CHECK (result IN ('DONE','FAILED')),
    result_detail  varchar(200) NULL
);
CREATE INDEX IF NOT EXISTS ix_lane_command_pending ON lane_device_command (device_id, created_at) WHERE done_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_lane_command_time ON lane_device_command (created_at);
