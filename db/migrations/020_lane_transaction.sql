-- 020: the lane controller. One transaction per truck at a lane: the reads from the lane's devices are gathered, the
-- truck is matched and re-checked, and the lane decides — admit (green, barrier open, ticket) or refer (red, a clerk
-- helps). The barrier's confirmation gates the truck in. Device reads and commands point to their transaction.

CREATE TABLE IF NOT EXISTS lane_transaction (
    transaction_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id       integer       NOT NULL REFERENCES terminal(terminal_id),
    lane_id           integer       NOT NULL REFERENCES gate_lane(lane_id) ON DELETE CASCADE,
    status            varchar(9)    NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','ADMITTED','REFERRED','PASSED','ABANDONED')),
    started_at        timestamptz   NOT NULL,
    last_read_at      timestamptz   NOT NULL,
    decided_at        timestamptz   NULL,
    closed_at         timestamptz   NULL,
    read_count        integer       NOT NULL DEFAULT 0,
    plate             varchar(20)   NULL,
    plate_confidence  smallint      NULL,
    containers        varchar(60)   NULL,   -- comma-separated, normalized
    tag               varchar(64)   NULL,
    appointment_read  varchar(30)   NULL,   -- typed at the kiosk
    qr_token          varchar(200)  NULL,   -- scanned gate pass; cleared once decided
    weight_kg         numeric(9,1)  NULL,
    appointment_id    bigint        NULL REFERENCES appointment(appointment_id) ON DELETE SET NULL,
    appointment_no    varchar(30)   NULL,
    trouble_id        bigint        NULL REFERENCES gate_trouble(trouble_id) ON DELETE SET NULL,
    reason            varchar(20)   NULL,   -- why referred (trouble reason, or EXIT for an exit the lane could not match)
    message           varchar(400)  NULL
);
CREATE INDEX IF NOT EXISTS ix_lane_tx_lane_time ON lane_transaction (lane_id, last_read_at);
CREATE INDEX IF NOT EXISTS ix_lane_tx_open ON lane_transaction (status, last_read_at) WHERE status = 'OPEN';

ALTER TABLE lane_device_read ADD COLUMN IF NOT EXISTS transaction_id bigint NULL REFERENCES lane_transaction(transaction_id) ON DELETE SET NULL;
ALTER TABLE lane_device_command ADD COLUMN IF NOT EXISTS transaction_id bigint NULL REFERENCES lane_transaction(transaction_id) ON DELETE SET NULL;
