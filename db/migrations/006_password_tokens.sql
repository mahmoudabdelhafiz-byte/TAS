-- Password reset and invitations (schema v0.6 -> v0.7).

CREATE TABLE password_token (   -- one-time links: forgotten password / invitation; only a SHA-256 hash is stored
    password_token_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer      NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    purpose           varchar(10)  NOT NULL CHECK (purpose IN ('RESET','INVITE')),
    token_hash        bytea        NOT NULL UNIQUE,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    expires_at        timestamptz  NOT NULL,
    used_at           timestamptz  NULL,
    created_ip        varchar(45)  NULL
);
CREATE INDEX ix_password_token_user ON password_token(user_id, created_at) WHERE used_at IS NULL;

ALTER TABLE notification_log ADD COLUMN payload text NULL;
