-- 023: inspection at the gate. Per container and passage (in / out): the seal checked against the one the company
-- declared, and the damage seen — by the lane cameras or a clerk — with photos. A trucking company can dispute an
-- inspection; terminal staff accept or reject with a note.

ALTER TABLE appointment_item ADD COLUMN IF NOT EXISTS seal_no varchar(20) NULL;   -- declared by the company

CREATE TABLE IF NOT EXISTS gate_inspection (
    inspection_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id     integer      NOT NULL REFERENCES terminal(terminal_id),
    appointment_id  bigint       NOT NULL REFERENCES appointment(appointment_id) ON DELETE CASCADE,
    stage           varchar(3)   NOT NULL CHECK (stage IN ('IN','OUT')),
    container_no    varchar(11)  NOT NULL DEFAULT '',   -- '' for cargo / the truck itself
    seal_expected   varchar(20)  NULL,
    seal_seen       varchar(20)  NULL,
    seal_status     varchar(11)  NOT NULL DEFAULT 'NOT_CHECKED' CHECK (seal_status IN ('OK','MISMATCH','MISSING','BROKEN','NOT_CHECKED')),
    damage_found    boolean      NOT NULL DEFAULT false,
    notes           varchar(400) NULL,
    source          varchar(6)   NOT NULL CHECK (source IN ('CAMERA','CLERK')),
    inspected_at    timestamptz  NOT NULL,
    inspected_by    integer      NULL,   -- app_user.user_id; NULL = the lane cameras
    UNIQUE (appointment_id, stage, container_no)
);
CREATE INDEX IF NOT EXISTS ix_inspection_terminal_time ON gate_inspection (terminal_id, inspected_at);

CREATE TABLE IF NOT EXISTS inspection_photo (
    photo_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id  bigint       NOT NULL REFERENCES gate_inspection(inspection_id) ON DELETE CASCADE,
    content_type   varchar(30)  NOT NULL,
    bytes          bytea        NOT NULL,
    size_bytes     integer      NOT NULL,
    uploaded_at    timestamptz  NOT NULL DEFAULT now(),
    uploaded_by    integer      NULL
);
CREATE INDEX IF NOT EXISTS ix_inspection_photo ON inspection_photo (inspection_id);

CREATE TABLE IF NOT EXISTS inspection_damage (
    damage_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id  bigint       NOT NULL REFERENCES gate_inspection(inspection_id) ON DELETE CASCADE,
    side           varchar(9)   NULL CHECK (side IN ('FRONT','REAR','LEFT','RIGHT','TOP','UNDERSIDE','INSIDE','DOOR')),   -- NULL: the camera didn't say
    kind           varchar(7)   NOT NULL CHECK (kind IN ('DENT','HOLE','CUT','SCRATCH','RUST','BROKEN','MISSING','WET','OTHER')),
    severity       varchar(5)   NOT NULL CHECK (severity IN ('MINOR','MAJOR')),
    note           varchar(200) NULL,
    photo_ref      varchar(400) NULL,   -- a camera system's picture
    photo_id       bigint       NULL REFERENCES inspection_photo(photo_id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS ix_inspection_damage ON inspection_damage (inspection_id);

CREATE TABLE IF NOT EXISTS inspection_dispute (
    dispute_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id    bigint       NOT NULL UNIQUE REFERENCES gate_inspection(inspection_id) ON DELETE CASCADE,
    company_id       integer      NOT NULL REFERENCES company(company_id),
    reason           varchar(600) NOT NULL,
    opened_by        integer      NOT NULL,   -- app_user.user_id
    opened_at        timestamptz  NOT NULL,
    status           varchar(8)   NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','ACCEPTED','REJECTED')),
    resolution_note  varchar(600) NULL,
    resolved_by      integer      NULL,
    resolved_at      timestamptz  NULL
);
CREATE INDEX IF NOT EXISTS ix_dispute_open ON inspection_dispute (status) WHERE status = 'OPEN';
