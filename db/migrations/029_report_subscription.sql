-- 029: reports by email. People (not necessarily portal users) get a daily summary (yesterday and today's bookings)
-- and / or a weekly one, with the figures as an Excel file, in their language. The hour and the weekday are terminal
-- settings (report_hour, report_weekday); the last day sent is kept so each report goes out once.

CREATE TABLE IF NOT EXISTS report_subscription (
    subscription_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id      integer      NOT NULL REFERENCES terminal(terminal_id),
    email            varchar(200) NOT NULL,
    language         char(2)      NOT NULL DEFAULT 'en',
    daily            boolean      NOT NULL DEFAULT true,
    weekly           boolean      NOT NULL DEFAULT false,
    created_at       timestamptz  NOT NULL DEFAULT now(),
    created_by       integer      NULL REFERENCES app_user(user_id),
    last_daily_on    date         NULL,   -- terminal-local day the daily report last went out
    last_weekly_on   date         NULL,
    UNIQUE (terminal_id, email)
);
