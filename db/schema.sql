/* =====================================================================
   Yardsyncs truck appointment system — PostgreSQL schema, draft v1.8
   Requires PostgreSQL 15+ and PostGIS (for geofences).
   Multi-terminal. See docs/data-model.md for the design.

   Conventions
   - snake_case names (EF Core: UseSnakeCaseNamingConvention)
   - all instants are timestamptz in UTC; the terminal's time zone
     (IANA, e.g. 'Asia/Riyadh') is applied when generating slots and
     when displaying times
   - template times are local wall-clock `time`, dates are `date`
   - optimistic concurrency uses PostgreSQL's xmin system column
     (no rowversion columns needed)
   - day_of_week: 0 = Sunday … 6 = Saturday (same as .NET DayOfWeek)
   ===================================================================== */

CREATE EXTENSION IF NOT EXISTS postgis;

/* ---------- 1. Terminal & configuration ---------- */

-- A terminal operator: runs one or more terminals on this installation (migration 014).
CREATE TABLE terminal_operator (
    operator_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         varchar(20)  NOT NULL UNIQUE,
    name         varchar(150) NOT NULL,
    is_active    boolean      NOT NULL DEFAULT true,
    created_at   timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE terminal (
    terminal_id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  varchar(20)  NOT NULL UNIQUE,
    name                  varchar(150) NOT NULL,
    terminal_type         varchar(20)  NOT NULL CHECK (terminal_type IN ('CONTAINER','MULTIPURPOSE')),
    time_zone             varchar(50)  NOT NULL DEFAULT 'Asia/Riyadh',
    slot_minutes          integer      NOT NULL DEFAULT 60 CHECK (slot_minutes IN (15,30,60,120)),
    booking_horizon_days  integer      NOT NULL DEFAULT 14 CHECK (booking_horizon_days BETWEEN 1 AND 90),
    is_active             boolean      NOT NULL DEFAULT true,
    operator_id           integer      NULL REFERENCES terminal_operator(operator_id),  -- NULL: no operator group
    created_at            timestamptz  NOT NULL DEFAULT now()
);

CREATE INDEX ix_terminal_operator ON terminal (operator_id) WHERE operator_id IS NOT NULL;

-- Name, colour, logo and web address: the installation's (operator_id NULL) and each operator's (migration 015).
CREATE TABLE branding (
    branding_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id  integer      NULL UNIQUE REFERENCES terminal_operator(operator_id) ON DELETE CASCADE,
    name         varchar(80)  NULL,
    color        char(7)      NULL CHECK (color ~ '^#[0-9a-f]{6}$'),
    domain       varchar(200) NULL UNIQUE,
    logo         bytea        NULL,
    logo_type    varchar(20)  NULL CHECK (logo_type IN ('image/png','image/jpeg','image/webp')),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX ux_branding_installation ON branding ((operator_id IS NULL)) WHERE operator_id IS NULL;

CREATE TABLE terminal_setting (
    terminal_id    integer      NOT NULL REFERENCES terminal(terminal_id),
    setting_key    varchar(60)  NOT NULL,   -- early_grace_min, late_grace_min, cancel_cutoff_min, max_appt_per_truck_per_day ...
    setting_value  varchar(400) NOT NULL,
    PRIMARY KEY (terminal_id, setting_key)
);

CREATE TABLE gate_lane (
    lane_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id  integer     NOT NULL REFERENCES terminal(terminal_id),
    gate_code    varchar(20) NOT NULL,
    lane_code    varchar(20) NOT NULL,
    direction    varchar(3)  NOT NULL CHECK (direction IN ('IN','OUT')),
    is_active    boolean     NOT NULL DEFAULT true,
    -- Autogate lane model (migration 018): state set by the gate staff, manual or automatic working.
    lane_state       varchar(12)  NOT NULL DEFAULT 'OPEN' CHECK (lane_state IN ('OPEN','CLOSED','OUT_OF_ORDER')),
    operation_mode   varchar(10)  NOT NULL DEFAULT 'MANUAL' CHECK (operation_mode IN ('MANUAL','AUTOMATIC')),
    state_note       varchar(200) NULL,
    state_changed_at timestamptz  NULL,
    state_changed_by integer      NULL,   -- app_user.user_id (app_user is created further down)
    UNIQUE (terminal_id, gate_code, lane_code)
);

-- The devices at a lane, vendor-neutral, with what each one reads (migration 018).
CREATE TABLE gate_lane_device (
    device_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id  integer      NOT NULL REFERENCES terminal(terminal_id),
    lane_id      integer      NOT NULL REFERENCES gate_lane(lane_id) ON DELETE CASCADE,
    device_code  varchar(30)  NOT NULL,
    kind         varchar(15)  NOT NULL CHECK (kind IN
                   ('CAMERA','OCR','RFID_READER','KIOSK','BARRIER','TRAFFIC_LIGHT','DISPLAY','PRINTER','INTERCOM','WEIGHBRIDGE')),
    reads        varchar(80)  NULL,   -- cameras / OCR: PLATE,CONTAINER,ISO_CODE,SEAL,DAMAGE; RFID readers: TAG
    vendor       varchar(60)  NULL,
    model        varchar(60)  NULL,
    address      varchar(200) NULL,   -- IP address, URL or port the lane controller uses
    is_active    boolean      NOT NULL DEFAULT true,
    notes        varchar(200) NULL,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    -- Device adapters (migration 019): the device's own key, and whether it is alive and healthy.
    key_hash         char(64)     NULL,   -- SHA-256 of the device key (hex)
    key_set_at       timestamptz  NULL,
    last_seen_at     timestamptz  NULL,
    reported_status  varchar(5)   NULL CHECK (reported_status IN ('OK','FAULT')),
    status_detail    varchar(200) NULL,
    UNIQUE (terminal_id, device_code)
);

CREATE INDEX ix_lane_device_lane ON gate_lane_device (lane_id);
CREATE UNIQUE INDEX ux_lane_device_key ON gate_lane_device (key_hash) WHERE key_hash IS NOT NULL;

-- What lane devices read, and the commands for them (migration 019).
CREATE TABLE lane_device_read (
    read_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id       integer      NOT NULL REFERENCES terminal(terminal_id),
    lane_id           integer      NOT NULL REFERENCES gate_lane(lane_id) ON DELETE CASCADE,
    device_id         integer      NOT NULL REFERENCES gate_lane_device(device_id) ON DELETE CASCADE,
    read_at           timestamptz  NOT NULL,                 -- when the device read it
    received_at       timestamptz  NOT NULL DEFAULT now(),
    plate             varchar(20)  NULL,                     -- normalized
    plate_confidence  smallint     NULL CHECK (plate_confidence BETWEEN 0 AND 100),
    container_no      varchar(11)  NULL,                     -- the first container read, normalized
    payload           jsonb        NOT NULL DEFAULT '{}'     -- the whole read, normalized: containers, seals, damage, photos, tag, kiosk entry, weight
);
CREATE INDEX ix_lane_read_lane_time ON lane_device_read (lane_id, received_at);
CREATE INDEX ix_lane_read_time ON lane_device_read (received_at);

CREATE TABLE lane_device_command (
    command_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id    integer      NOT NULL REFERENCES terminal(terminal_id),
    lane_id        integer      NOT NULL REFERENCES gate_lane(lane_id) ON DELETE CASCADE,
    device_id      integer      NOT NULL REFERENCES gate_lane_device(device_id) ON DELETE CASCADE,
    command        varchar(6)   NOT NULL CHECK (command IN ('OPEN','CLOSE','RED','GREEN','OFF','SHOW','CLEAR','PRINT','CALL','HANGUP')),
    text           varchar(400) NULL,                        -- display / ticket text
    created_at     timestamptz  NOT NULL DEFAULT now(),
    created_by     integer      NULL,                        -- app_user.user_id; NULL = the lane itself
    expires_at     timestamptz  NOT NULL,                    -- not carried out after this (a late barrier opening is unsafe)
    delivered_at   timestamptz  NULL,
    done_at        timestamptz  NULL,
    result         varchar(6)   NULL CHECK (result IN ('DONE','FAILED')),
    result_detail  varchar(200) NULL
);
CREATE INDEX ix_lane_command_pending ON lane_device_command (device_id, created_at) WHERE done_at IS NULL;
CREATE INDEX ix_lane_command_time ON lane_device_command (created_at);

CREATE TABLE transaction_category (
    category_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id  integer      NOT NULL REFERENCES terminal(terminal_id),
    code         varchar(30)  NOT NULL,   -- IMP_PICKUP, EXP_DROP, MTY_RETURN, MTY_PICKUP, BB_DELIVERY, BULK_DELIVERY, RORO_PICKUP ...
    name_en      varchar(100) NOT NULL,
    name_ar      varchar(100) NOT NULL,
    mode         varchar(10)  NOT NULL CHECK (mode IN ('CONTAINER','CARGO')),
    unit_type    varchar(10)  NOT NULL DEFAULT 'MOVE' CHECK (unit_type IN ('MOVE','TRIP')),
    sort_order   integer      NOT NULL DEFAULT 0,
    is_active    boolean      NOT NULL DEFAULT true,
    UNIQUE (terminal_id, code),
    flow         varchar(3)   NULL CHECK (flow IN ('IN','OUT'))   -- IN: brought into the terminal; OUT: taken out (migration 024)
);

/* ---------- 2. Capacity configuration ---------- */

CREATE TABLE capacity_template (
    template_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id  integer      NOT NULL REFERENCES terminal(terminal_id),
    name         varchar(100) NOT NULL,       -- 'Default', 'Ramadan 2027', 'Summer'
    is_default   boolean      NOT NULL DEFAULT false,
    valid_from   date         NULL,           -- NULL for default
    valid_to     date         NULL,
    priority     integer      NOT NULL DEFAULT 0,  -- higher wins among overlapping seasonal templates
    is_active    boolean      NOT NULL DEFAULT true,
    CONSTRAINT ck_template_dates CHECK (
        (is_default AND valid_from IS NULL AND valid_to IS NULL) OR
        (NOT is_default AND valid_from IS NOT NULL AND valid_to IS NOT NULL AND valid_to >= valid_from))
);
-- only one active default template per terminal
CREATE UNIQUE INDEX ux_template_default ON capacity_template(terminal_id) WHERE is_default AND is_active;

CREATE TABLE capacity_template_slot (
    template_slot_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id       integer      NOT NULL REFERENCES capacity_template(template_id) ON DELETE CASCADE,
    day_of_week       smallint     NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    start_time        time(0)      NOT NULL,
    end_time          time(0)      NOT NULL,   -- window; generator splits it by terminal.slot_minutes
    total_capacity    integer      NOT NULL CHECK (total_capacity >= 0),  -- per generated slot
    overbook_pct      numeric(5,2) NOT NULL DEFAULT 0 CHECK (overbook_pct >= 0),
    CONSTRAINT ck_template_slot_time CHECK (end_time > start_time)
);

CREATE TABLE capacity_template_quota (
    template_slot_id  integer NOT NULL REFERENCES capacity_template_slot(template_slot_id) ON DELETE CASCADE,
    category_id       integer NOT NULL REFERENCES transaction_category(category_id),
    max_units         integer NOT NULL CHECK (max_units >= 0),
    PRIMARY KEY (template_slot_id, category_id)
);

CREATE TABLE capacity_override (
    override_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id  integer      NOT NULL REFERENCES terminal(terminal_id),
    start_at     timestamptz  NOT NULL,
    end_at       timestamptz  NOT NULL,
    category_id  integer      NULL REFERENCES transaction_category(category_id),  -- NULL = slot total
    action       varchar(10)  NOT NULL CHECK (action IN ('SET','ADJUST','CLOSE')),
    value        integer      NULL,       -- ignored for CLOSE; may be negative for ADJUST
    reason       varchar(300) NOT NULL,
    is_active    boolean      NOT NULL DEFAULT true,
    created_by   integer      NOT NULL,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_override_time  CHECK (end_at > start_at),
    CONSTRAINT ck_override_value CHECK (action = 'CLOSE' OR value IS NOT NULL)
);
CREATE INDEX ix_override_range ON capacity_override(terminal_id, start_at, end_at) WHERE is_active;

CREATE TABLE quota_release_rule (
    terminal_id   integer NOT NULL REFERENCES terminal(terminal_id),
    category_id   integer NOT NULL REFERENCES transaction_category(category_id),
    hours_before  integer NOT NULL CHECK (hours_before >= 0),  -- unused quota opens to pool this many hours before slot start
    PRIMARY KEY (terminal_id, category_id)
);

/* ---------- 3. Parties ---------- */

CREATE TABLE company (
    company_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(200) NOT NULL,
    cr_number      varchar(30)  NULL,
    company_type   varchar(20)  NOT NULL CHECK (company_type IN ('TRUCKING','FORWARDER','CONSIGNEE','LINE','OTHER')),
    is_priority    boolean      NOT NULL DEFAULT false,
    status         varchar(15)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('PENDING','ACTIVE','SUSPENDED')),
    no_show_count  integer      NOT NULL DEFAULT 0,
    created_at     timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE app_user (
    user_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id          integer      NULL REFERENCES company(company_id),    -- NULL for terminal staff
    terminal_id         integer      NULL REFERENCES terminal(terminal_id),  -- set for terminal staff
    operator_id         integer      NULL REFERENCES terminal_operator(operator_id),  -- set for operator admins
    email               varchar(200) NOT NULL UNIQUE,
    mobile              varchar(20)  NULL,
    full_name           varchar(150) NOT NULL,
    role                varchar(20)  NOT NULL CHECK (role IN ('COMPANY_ADMIN','COMPANY_USER','GATE_CLERK','PLANNER','TERMINAL_ADMIN','OPERATOR_ADMIN','SYS_ADMIN')),
    preferred_language  char(2)      NOT NULL DEFAULT 'en',
    is_active           boolean      NOT NULL DEFAULT true,
    -- authentication
    password_hash       varchar(200) NULL,         -- ASP.NET Core Identity hash; NULL = no password set yet
    failed_login_count  integer      NOT NULL DEFAULT 0,
    locked_until        timestamptz  NULL,
    last_login_at       timestamptz  NULL,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    -- two-step sign-in (see migration 028)
    totp_secret         bytea        NULL,
    totp_enabled_at     timestamptz  NULL,
    totp_last_step      bigint       NULL
);

-- Links to set a password (see migration 010).
CREATE TABLE password_token (
    token_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      integer      NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    purpose      varchar(10)  NOT NULL CHECK (purpose IN ('RESET','INVITE')),
    token_hash   bytea        NOT NULL UNIQUE,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    expires_at   timestamptz  NOT NULL,
    used_at      timestamptz  NULL,
    created_by   integer      NULL REFERENCES app_user(user_id)
);
CREATE INDEX ix_password_token_user ON password_token(user_id, created_at);

CREATE TABLE refresh_token (   -- rotating refresh tokens; only a SHA-256 hash is stored
    refresh_token_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer      NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    token_hash        bytea        NOT NULL UNIQUE,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    expires_at        timestamptz  NOT NULL,
    revoked_at        timestamptz  NULL,
    replaced_by_hash  bytea        NULL,
    created_ip        varchar(45)  NULL
);
CREATE INDEX ix_refresh_token_user ON refresh_token(user_id) WHERE revoked_at IS NULL;

CREATE TABLE truck (
    truck_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id        integer     NOT NULL REFERENCES company(company_id),
    plate_number      varchar(20) NOT NULL,   -- as entered (Arabic/Latin)
    plate_normalized  varchar(20) NOT NULL UNIQUE,  -- uppercase Latin, no spaces; used for OCR matching
    is_blocked        boolean     NOT NULL DEFAULT false
);

CREATE TABLE driver (
    driver_id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id          integer      NOT NULL REFERENCES company(company_id),
    full_name           varchar(150) NOT NULL,
    id_number           varchar(30)  NOT NULL,
    mobile              varchar(20)  NOT NULL,
    preferred_language  char(2)      NOT NULL DEFAULT 'ar',  -- ar / en / ur / hi
    is_blocked          boolean      NOT NULL DEFAULT false,
    UNIQUE (company_id, id_number)
);

/* ---------- 4. Materialized capacity ---------- */

CREATE TABLE slot (
    slot_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id     integer     NOT NULL REFERENCES terminal(terminal_id),
    start_at        timestamptz NOT NULL,
    end_at          timestamptz NOT NULL,
    total_capacity  integer     NOT NULL CHECK (total_capacity >= 0),  -- effective, incl. overrides + overbook
    total_booked    integer     NOT NULL DEFAULT 0 CHECK (total_booked >= 0),
    is_closed       boolean     NOT NULL DEFAULT false,
    over_capacity   boolean     NOT NULL DEFAULT false,   -- set when regenerated capacity < booked
    generated_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (terminal_id, start_at),
    CONSTRAINT ck_slot_time CHECK (end_at > start_at)
);

CREATE TABLE slot_category_capacity (
    slot_id         bigint  NOT NULL REFERENCES slot(slot_id) ON DELETE CASCADE,
    category_id     integer NOT NULL REFERENCES transaction_category(category_id),
    quota_capacity  integer NOT NULL CHECK (quota_capacity >= 0),
    booked          integer NOT NULL DEFAULT 0 CHECK (booked >= 0),
    PRIMARY KEY (slot_id, category_id)
);

CREATE TABLE capacity_reservation (
    reservation_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id           integer     NOT NULL REFERENCES terminal(terminal_id),
    company_id            integer     NULL REFERENCES company(company_id),  -- NULL = walk-in / emergency reserve
    category_id           integer     NULL REFERENCES transaction_category(category_id),
    start_at              timestamptz NOT NULL,
    end_at                timestamptz NOT NULL,
    units_per_slot        integer     NOT NULL CHECK (units_per_slot > 0),
    release_hours_before  integer     NOT NULL DEFAULT 0 CHECK (release_hours_before >= 0),
    is_active             boolean     NOT NULL DEFAULT true,
    CONSTRAINT ck_reservation_time CHECK (end_at > start_at)
);

/* ---------- 5. Multipurpose cargo ---------- */

CREATE TABLE cargo_allocation (
    cargo_allocation_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id          integer       NOT NULL REFERENCES terminal(terminal_id),
    company_id           integer       NULL REFERENCES company(company_id),
    cargo_ref            varchar(50)   NOT NULL,   -- BL / delivery order / cargo ref
    vessel_visit_ref     varchar(50)   NULL,
    commodity            varchar(150)  NULL,
    cargo_type           varchar(15)   NOT NULL CHECK (cargo_type IN ('BREAKBULK','BULK','RORO','PROJECT')),
    total_tonnage        numeric(12,3) NULL,
    total_trips          integer       NULL,
    delivered_tonnage    numeric(12,3) NOT NULL DEFAULT 0,
    booked_trips         integer       NOT NULL DEFAULT 0,
    status               varchar(15)   NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','HOLD','CLOSED')),
    UNIQUE (terminal_id, cargo_ref)
);

/* ---------- 6. Booking ---------- */

CREATE TABLE appointment (
    appointment_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_no   varchar(20)  NOT NULL UNIQUE,
    terminal_id      integer      NOT NULL REFERENCES terminal(terminal_id),
    slot_id          bigint       NOT NULL REFERENCES slot(slot_id),
    company_id       integer      NOT NULL REFERENCES company(company_id),
    truck_id         integer      NULL REFERENCES truck(truck_id),    -- can be assigned after booking
    driver_id        integer      NULL REFERENCES driver(driver_id),
    status           varchar(20)  NOT NULL DEFAULT 'CONFIRMED' CHECK (status IN
                       ('DRAFT','CONFIRMED','EN_ROUTE','ARRIVED','GATE_IN','COMPLETED','CANCELLED','NO_SHOW','REJECTED_AT_GATE')),
    is_dual          boolean      NOT NULL DEFAULT false,
    qr_token         varchar(64)  NOT NULL UNIQUE,
    -- driver app / tracking (latest values; history in appointment_eta & geofence_event)
    traffic_light    varchar(6)   NOT NULL DEFAULT 'GREY' CHECK (traffic_light IN ('GREY','GREEN','AMBER','RED')),
    traffic_reason   varchar(200) NULL,       -- shown to driver, e.g. 'Customs hold' / 'Outside time window'
    current_eta      timestamptz  NULL,
    eta_updated_at   timestamptz  NULL,
    last_latitude    numeric(9,6) NULL,       -- last app position (on the way / inside only), for the control room
    last_longitude   numeric(9,6) NULL,
    last_position_at timestamptz  NULL,
    check_in_method  varchar(15)  NULL CHECK (check_in_method IN ('APP_GEOFENCE','APP_MANUAL','OCR','CLERK')),
    last_validated_at timestamptz NULL,      -- last time the items were (re-)checked against the TOS
    arrived_at       timestamptz  NULL,
    gate_in_at       timestamptz  NULL,
    gate_out_at      timestamptz  NULL,
    created_by       integer      NOT NULL REFERENCES app_user(user_id),
    created_at       timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_appt_slot  ON appointment(slot_id, status);
CREATE INDEX ix_appt_truck ON appointment(truck_id, status);
CREATE INDEX ix_appt_revalidation ON appointment(status, last_validated_at);

CREATE TABLE appointment_item (
    item_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id       bigint        NOT NULL REFERENCES appointment(appointment_id) ON DELETE CASCADE,
    category_id          integer       NOT NULL REFERENCES transaction_category(category_id),
    -- container moves
    container_no         varchar(11)   NULL,
    iso_type             varchar(4)    NULL,
    booking_ref          varchar(50)   NULL,   -- export booking
    edo_ref              varchar(50)   NULL,   -- import delivery order
    -- cargo moves
    cargo_allocation_id  integer       NULL REFERENCES cargo_allocation(cargo_allocation_id),
    trips                integer       NULL CHECK (trips IS NULL OR trips > 0),
    planned_tonnage      numeric(12,3) NULL,
    actual_tonnage       numeric(12,3) NULL,
    -- validation
    validation_status    varchar(10)   NOT NULL DEFAULT 'PENDING' CHECK (validation_status IN ('PENDING','PASS','WARN','FAIL')),
    tos_ref              varchar(50)   NULL,   -- e.g. N4 pre-advice / truck visit key
    CONSTRAINT ck_item_kind CHECK (
        (container_no IS NOT NULL AND cargo_allocation_id IS NULL) OR
        (container_no IS NULL AND cargo_allocation_id IS NOT NULL) OR
        (container_no IS NULL AND cargo_allocation_id IS NULL AND booking_ref IS NOT NULL)  -- empty pickup by booking only
    ),
    seal_no             varchar(20)  NULL   -- declared by the company (migration 023)
);
CREATE INDEX ix_item_container ON appointment_item(container_no) WHERE container_no IS NOT NULL;

CREATE TABLE validation_result (
    validation_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id        bigint       NOT NULL REFERENCES appointment_item(item_id) ON DELETE CASCADE,
    check_type     varchar(20)  NOT NULL,   -- AVAILABILITY, CUSTOMS_RELEASE, LINE_RELEASE, TERMINAL_HOLD, PAYMENT, BOOKING_VALID, VGM, CUTOFF
    result         varchar(4)   NOT NULL CHECK (result IN ('PASS','WARN','FAIL')),
    message        varchar(400) NULL,
    source         varchar(20)  NOT NULL,   -- N4, FASAH, INTERNAL
    checked_at     timestamptz  NOT NULL DEFAULT now()
);

-- Fees charged for an appointment, once per kind; waived ones stay with who waived them and why (migration 017).
CREATE TABLE appointment_charge (
    charge_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id     integer      NOT NULL REFERENCES terminal(terminal_id),
    appointment_id  bigint       NOT NULL REFERENCES appointment(appointment_id) ON DELETE CASCADE,
    company_id      integer      NOT NULL REFERENCES company(company_id),
    kind            varchar(12)  NOT NULL CHECK (kind IN ('BOOKING','NO_SHOW','LATE_CANCEL')),
    amount_minor    bigint       NOT NULL CHECK (amount_minor > 0),
    currency        char(3)      NOT NULL,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    waived_at       timestamptz  NULL,
    waived_by       integer      NULL REFERENCES app_user(user_id),
    waive_reason    varchar(300) NULL,
    UNIQUE (appointment_id, kind)
);

CREATE INDEX ix_charge_terminal_time ON appointment_charge (terminal_id, created_at);

CREATE TABLE appointment_status_history (
    history_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  bigint       NOT NULL REFERENCES appointment(appointment_id) ON DELETE CASCADE,
    from_status     varchar(20)  NULL,
    to_status       varchar(20)  NOT NULL,
    changed_by      integer      NULL REFERENCES app_user(user_id),  -- NULL = system
    reason          varchar(300) NULL,
    changed_at      timestamptz  NOT NULL DEFAULT now()
);

/* ---------- 7. Gate ---------- */

CREATE TABLE gate_event (
    gate_event_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terminal_id     integer      NOT NULL REFERENCES terminal(terminal_id),
    lane_id         integer      NULL REFERENCES gate_lane(lane_id),
    appointment_id  bigint       NULL REFERENCES appointment(appointment_id),  -- NULL until matched
    event_type      varchar(15)  NOT NULL CHECK (event_type IN
                      ('OCR_READ','APP_CHECKIN','PASS_SCAN','MATCHED','NO_APPT','EARLY','LATE','GATE_IN','GATE_OUT','TROUBLE')),
    plate_read      varchar(20)  NULL,
    container_read  varchar(11)  NULL,
    details         varchar(400) NULL,
    occurred_at     timestamptz  NOT NULL
);
CREATE INDEX ix_gate_time ON gate_event(terminal_id, occurred_at);

-- Trouble desk: trucks at the gate that could not be admitted automatically.
